const fs = require('fs');

const L = [];
const p = (s) => L.push(s);

p("let SUPABASE_URL = (process.env.SUPABASE_URL || '')");
p("  .replace(/\\/+$/, '').replace(/\\/rest\\/v1.*$/, '').replace(/\\/+$/, '');");
p("const SUPABASE_KEY = process.env.SUPABASE_KEY;");
p("const headers = {");
p("  apikey: SUPABASE_KEY,");
p("  Authorization: 'Bearer ' + SUPABASE_KEY,");
p("  'Content-Type': 'application/json',");
p("};");
p("(async () => {");
p("  console.log('\\n=== NORMALIZE POSITIONS (loops until clean) ===\\n');");
p("  const pairs = [['Aye', 'Yea'], ['No', 'Nay']];");
p("  for (const pr of pairs) {");
p("    const from = pr[0];");
p("    const to = pr[1];");
p("    let pass = 0;");
p("    while (pass < 30) {");
p("      const cRes = await fetch(SUPABASE_URL + '/rest/v1/member_votes?position=eq.' + from + '&select=id&limit=1', { headers: headers });");
p("      const rows = await cRes.json();");
p("      if (!Array.isArray(rows) || rows.length === 0) break;");
p("      const upd = await fetch(SUPABASE_URL + '/rest/v1/member_votes?position=eq.' + from, {");
p("        method: 'PATCH', headers: headers, body: JSON.stringify({ position: to })");
p("      });");
p("      if (!upd.ok) { console.log('  ' + from + ': FAILED ' + upd.status); break; }");
p("      pass++;");
p("      console.log('  ' + from + ' -> ' + to + ': pass ' + pass);");
p("    }");
p("    if (pass === 0) console.log('  ' + from + ': already clean');");
p("  }");
p("  console.log('\\nverifying...');");
p("  const check = {};");
p("  for (const val of ['Yea', 'Nay', 'Aye', 'No', 'Present', 'Not Voting']) {");
p("    const r = await fetch(SUPABASE_URL + '/rest/v1/member_votes?position=eq.' + encodeURIComponent(val) + '&select=id&limit=1', { headers: headers });");
p("    const rows = await r.json();");
p("    check[val] = (Array.isArray(rows) && rows.length) ? 'present' : 'none';");
p("  }");
p("  console.log(JSON.stringify(check, null, 2));");
p("  console.log('');");
p("})();");

fs.writeFileSync('normalize-positions.js', L.join('\n'), 'utf8');
console.log('\nWrote normalize-positions.js (looping version)\n');