const fs = require('fs');

const L = [];
const p = (s) => L.push(s);

p("let SUPABASE_URL = (process.env.SUPABASE_URL || '')");
p("  .replace(/\\/+$/, '').replace(/\\/rest\\/v1.*$/, '').replace(/\\/+$/, '');");
p("const SUPABASE_KEY = process.env.SUPABASE_KEY;");
p("const headers = {");
p("  apikey: SUPABASE_KEY,");
p("  Authorization: 'Bearer ' + SUPABASE_KEY,");
p("  'Content-Type': 'application/json',");
p("  Prefer: 'resolution=merge-duplicates',");
p("};");
p("const ABBR = {Alabama:'AL',Alaska:'AK',Arizona:'AZ',Arkansas:'AR',California:'CA',Colorado:'CO',Connecticut:'CT',Delaware:'DE',Florida:'FL',Georgia:'GA',Hawaii:'HI',Idaho:'ID',Illinois:'IL',Indiana:'IN',Iowa:'IA',Kansas:'KS',Kentucky:'KY',Louisiana:'LA',Maine:'ME',Maryland:'MD',Massachusetts:'MA',Michigan:'MI',Minnesota:'MN',Mississippi:'MS',Missouri:'MO',Montana:'MT',Nebraska:'NE',Nevada:'NV','New Hampshire':'NH','New Jersey':'NJ','New Mexico':'NM','New York':'NY','North Carolina':'NC','North Dakota':'ND',Ohio:'OH',Oklahoma:'OK',Oregon:'OR',Pennsylvania:'PA','Rhode Island':'RI','South Carolina':'SC','South Dakota':'SD',Tennessee:'TN',Texas:'TX',Utah:'UT',Vermont:'VT',Virginia:'VA',Washington:'WA','West Virginia':'WV',Wisconsin:'WI',Wyoming:'WY'};");
p("function tag(xml, name) {");
p("  const re = new RegExp('<' + name + '>([\\\\s\\\\S]*?)<\\\\/' + name + '>');");
p("  const m = xml.match(re);");
p("  return m ? m[1].trim() : '';");
p("}");
p("(async () => {");
p("  console.log('\\n=== BACKFILL SENATE MEMBER VOTES ===\\n');");
p("  const memRes = await fetch(SUPABASE_URL + '/rest/v1/members?chamber=eq.Senate&select=bioguide_id,last_name,state', { headers: headers });");
p("  const senators = await memRes.json();");
p("  const lookup = {};");
p("  senators.forEach(function (s) {");
p("    const ab = ABBR[s.state] || s.state;");
p("    lookup[(s.last_name || '').toLowerCase() + '|' + String(ab).toUpperCase()] = s.bioguide_id;");
p("  });");
p("  console.log('senators indexed: ' + Object.keys(lookup).length);");
p("  const vRes = await fetch(SUPABASE_URL + '/rest/v1/votes?chamber=eq.Senate&select=id,congress,session,roll_call&order=roll_call.asc', { headers: headers });");
p("  const votes = await vRes.json();");
p("  console.log('senate votes stored: ' + votes.length + '\\n');");
p("  let total = 0;");
p("  for (const v of votes) {");
p("    const existRes = await fetch(SUPABASE_URL + '/rest/v1/member_votes?vote_id=eq.' + v.id + '&select=id&limit=1', { headers: headers });");
p("    const already = await existRes.json();");
p("    if (Array.isArray(already) && already.length) { console.log('roll ' + v.roll_call + ': already has member votes'); continue; }");
p("    const padded = String(v.roll_call).padStart(5, '0');");
p("    const url = 'https://www.senate.gov/legislative/LIS/roll_call_votes/vote' + v.congress + v.session + '/vote_' + v.congress + '_' + v.session + '_' + padded + '.xml';");
p("    try {");
p("      const res = await fetch(url, { headers: { 'User-Agent': 'CivicLens/1.0' } });");
p("      if (!res.ok) { console.log('roll ' + v.roll_call + ': fetch ' + res.status); continue; }");
p("      const xml = await res.text();");
p("      const memberBlocks = xml.split('<member>').slice(1);");
p("      const rows = [];");
p("      let unmatched = 0;");
p("      for (const mb of memberBlocks) {");
p("        const ln = tag(mb, 'last_name');");
p("        const st = tag(mb, 'state');");
p("        const cast = tag(mb, 'vote_cast');");
p("        const bio = lookup[(ln || '').toLowerCase() + '|' + (st || '').toUpperCase()];");
p("        if (!bio) { unmatched++; continue; }");
p("        rows.push({ vote_id: v.id, bioguide_id: bio, position: cast });");
p("      }");
p("      if (rows.length) {");
p("        const ins = await fetch(SUPABASE_URL + '/rest/v1/member_votes', { method: 'POST', headers: headers, body: JSON.stringify(rows) });");
p("        if (ins.ok || ins.status === 201) {");
p("          total += rows.length;");
p("          console.log('roll ' + v.roll_call + ': saved ' + rows.length + (unmatched ? ' (' + unmatched + ' unmatched)' : ''));");
p("        } else {");
p("          console.log('roll ' + v.roll_call + ': FAILED ' + ins.status + ' ' + (await ins.text()).substring(0, 150));");
p("        }");
p("      } else {");
p("        console.log('roll ' + v.roll_call + ': no matches (' + unmatched + ' unmatched)');");
p("      }");
p("    } catch (e) {");
p("      console.log('roll ' + v.roll_call + ': ERROR ' + e.message);");
p("    }");
p("  }");
p("  console.log('\\nDone. ' + total + ' member votes saved.\\n');");
p("})();");

fs.writeFileSync('backfill-senate-member-votes.js', L.join('\n'), 'utf8');
console.log('\nWrote backfill-senate-member-votes.js\n');